"""Ephemeral disk-backed SQLite rehearsal of v0.2 atomic events.

Only TemporaryDirectory-created files; no operator path, Oracle, provider,
network or real collector. "Reopen" is NOT a simulated OS power failure.
WAL journaling and a successful database integrity_check do not authenticate
an external first-seen timestamp.
"""
from __future__ import annotations

import sqlite3
from pathlib import Path
from tempfile import TemporaryDirectory

from cot_atomic_ingest_v02_lab import AtomicOfflineCOTStore
from cot_revision_lineage_v01_lab import RevisionError


class EphemeralWALReopen:
    """Bootstraps v0.2's in-memory schema into an automatically cleaned fixture."""

    def __init__(self, *, synthetic=False):
        if synthetic is not True:
            raise RevisionError("ephemeral_fixture_opt_in_required")
        self._temp = TemporaryDirectory(prefix="remura-cot-v03-fixture-")
        self._path = Path(self._temp.name) / "cot_fixture.sqlite3"
        initial = AtomicOfflineCOTStore(synthetic=True)
        disk = None
        try:
            disk = sqlite3.connect(str(self._path), isolation_level=None)
            initial._db.backup(disk)
            mode = disk.execute("PRAGMA journal_mode=WAL").fetchone()[0]
            if mode.lower() != "wal":
                raise RevisionError("ephemeral_wal_unavailable")
            disk.execute("PRAGMA foreign_keys=ON")
            disk.close()
            disk = None
            initial.close()
            self.store = AtomicOfflineCOTStore(synthetic=True)
            self.store._db.close()
            self.store._db = self._connect()
        except BaseException:
            if disk is not None:
                disk.close()
            initial.close()
            self._temp.cleanup()
            raise

    def _connect(self):
        # Fixed path generated by TemporaryDirectory, never from callers.
        con = sqlite3.connect(str(self._path), isolation_level=None, timeout=0)
        con.execute("PRAGMA foreign_keys=ON")
        con.execute("PRAGMA busy_timeout=0")
        if con.execute("PRAGMA journal_mode").fetchone()[0].lower() != "wal":
            con.close()
            raise RevisionError("ephemeral_wal_lost")
        return con

    def reopen(self):
        self.store._db.close()
        self.store._db = self._connect()
        self.assert_integrity()
        return self.store

    def assert_integrity(self):
        check = self.store._db.execute("PRAGMA integrity_check").fetchone()[0]
        if check != "ok":
            raise RevisionError("fixture_integrity_check_failure")
        return check

    def journal_mode(self):
        return self.store._db.execute("PRAGMA journal_mode").fetchone()[0]

    def fixture_file_exists(self):
        return self._path.is_file()

    def close(self):
        try:
            self.store.close()
        finally:
            self._temp.cleanup()
